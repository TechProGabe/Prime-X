#!/usr/bin/env python3
"""Write xbox/src/sdk/disc_table.inc: what a clean Metroid Prime USA 1.00
(GM8E01 rev 0) image holds, for the boot-time disc check (docs/boot-safety.md).

  python tools/disc_file_table.py "<GM8E01 rev 0 image.iso>"

Refuses any image but the Redump one (its SHA-1 below). Writes hashes, sizes,
offsets and the disc's file names only: no game data.
"""
import hashlib
import pathlib
import struct
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'xbox/src/sdk/disc_table.inc'
SHA1 = 'ac20c744db18fdf0339f37945e880708fd317231'
SIZE = 1459978240
# the other releases, so the error screen can name them (MetroidPrimePort's
# platform/port_disc_verify_table.inc)
OTHERS = [('GM8E01', 1, 'USA 1.01'), ('GM8E01', 2, 'USA 1.02'), ('GM8P01', 0, 'PAL'),
          ('GM8J01', 0, 'Japan')]


def be32(b, o):
    return struct.unpack_from('>I', b, o)[0]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = sys.argv[1]
    f = open(path, 'rb')
    data_size = f.seek(0, 2)
    if data_size != SIZE:
        sys.exit(f'{path}: {data_size} bytes, a clean USA 1.00 image is {SIZE}')
    print('hashing the image...', file=sys.stderr)
    h = hashlib.sha1()
    f.seek(0)
    for block in iter(lambda: f.read(1 << 22), b''):
        h.update(block)
    if h.hexdigest() != SHA1:
        sys.exit(f'{path}: SHA-1 {h.hexdigest()}, not the Redump USA 1.00 image ({SHA1})')

    def read(off, n):
        f.seek(off)
        return f.read(n)

    hdr = read(0, 0x440)
    dol_off, fst_off, fst_len = be32(hdr, 0x420), be32(hdr, 0x424), be32(hdr, 0x428)
    dolh = read(dol_off, 0x100)
    dol_len = max(be32(dolh, i * 4) + be32(dolh, 0x90 + i * 4) for i in range(18) if be32(dolh, 0x90 + i * 4))
    appl = read(0x2440, 0x20)
    appl_len = 0x20 + be32(appl, 0x14) + be32(appl, 0x18)
    fst = read(fst_off, fst_len)

    def crc(off, n):
        return zlib.crc32(read(off, n)) & 0xFFFFFFFF

    n = be32(fst, 8)
    names = n * 12
    files = []
    stack = []
    i = 1
    while i < n:
        while stack and i >= stack[-1][1]:
            stack.pop()
        word, off, size = struct.unpack_from('>III', fst, i * 12)
        end = fst.index(b'\0', names + (word & 0xFFFFFF))
        name = fst[names + (word & 0xFFFFFF):end].decode('ascii')
        full = (stack[-1][0] if stack else '') + name
        if word >> 24:
            stack.append((full + '/', size))
        else:
            files.append((full, off, size, crc(off, size)))
        i += 1

    lines = [
        '/* disc_table.inc - a clean Metroid Prime USA 1.00 (GM8E01 rev 0) image, for',
        ' * the boot-time disc check (dvd.c, docs/boot-safety.md). Generated by',
        ' * tools/disc_file_table.py from the Redump image; do not edit. */',
        f'#define DISC_IMAGE_SIZE {SIZE}u',
        f'#define DISC_IMAGE_SHA1 "{SHA1}"',
        f'#define DISC_FST_ENTRIES {n}u',
        f'#define DISC_FST_SIZE {fst_len}u',
        f'#define DISC_FST_CRC 0x{zlib.crc32(fst) & 0xFFFFFFFF:08X}u',
        f'#define DISC_BOOT_CRC 0x{crc(0, 0x440):08X}u',
        f'#define DISC_BI2_CRC 0x{crc(0x440, 0x2000):08X}u',
        f'#define DISC_APPLOADER_SIZE {appl_len}u',
        f'#define DISC_APPLOADER_CRC 0x{crc(0x2440, appl_len):08X}u',
        f'#define DISC_DOL_OFFSET {dol_off}u',
        f'#define DISC_DOL_SIZE {dol_len}u',
        f'#define DISC_DOL_CRC 0x{crc(dol_off, dol_len):08X}u',
        f'#define DISC_FILE_COUNT {len(files)}u',
        '',
        'static const DiscFile k_disc_files[DISC_FILE_COUNT] = {',
    ]
    lines += [f'    {{ "{p}", {o}u, {s}u, 0x{c:08X}u }},' for p, o, s, c in files]
    lines += ['};', '', 'static const DiscRelease k_disc_others[] = {']
    lines += [f'    {{ "{i}", {v}, "{name}" }},' for i, v, name in OTHERS]
    lines += ['};', '']
    OUT.write_text('\n'.join(lines), newline='\n')
    print(f'{len(files)} files -> {OUT.relative_to(ROOT)}', file=sys.stderr)


if __name__ == '__main__':
    main()
