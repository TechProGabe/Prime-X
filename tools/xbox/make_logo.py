#!/usr/bin/env python3
"""Draw the Prime-X dashboard icon: a bold bevelled X on a dark visor-glass
badge with a scan reticle around it (transparent background).

  tools/xbox/make_logo.py <out.png> [size]

Melee-X's icon (Melee-X tools/xbox/make_logo.py), remixed for Prime: the
steel rim and bevelled X stay, the face becomes dark teal visor glass with a
cyan scan ring and corner brackets, and the X takes the Varia suit's
orange-to-red. Drawn from scratch with Pillow (no game or console art), so it
can live in the repo. xbox/assets/logo.png is generated by this; the XBE's
$$XTIMAGE and default.tbn will come from it (xbe_title_image.py, imported
from Melee-X in phase 1).
"""
import math
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter

S = 1024  # work size; downscaled at the end for smooth edges
C = S / 2


def bar(angle, length, width, cut):
    """A bar through the centre at `angle`, its ends cut at 45 degrees the
    way the arms of an X meet the badge: a hexagon."""
    ux, uy = math.cos(angle), math.sin(angle)
    nx, ny = -uy, ux
    h, w = length / 2, width / 2
    pts = [(h, w - cut), (h - cut, w), (-h + cut, w), (-h, w - cut), (-h, -w + cut), (-h + cut, -w), (h - cut, -w),
           (h, -w + cut)]
    return [(C + x * ux + y * nx, C + x * uy + y * ny) for x, y in pts]


def x_mask(length, width, cut):
    m = Image.new("L", (S, S), 0)
    d = ImageDraw.Draw(m)
    d.polygon(bar(math.radians(45), length, width, cut), fill=255)
    d.polygon(bar(math.radians(-45), length, width, cut), fill=255)
    return m


def vgrad(top, bot, y0=0, y1=S):
    g = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(g)
    for y in range(S):
        t = min(1.0, max(0.0, (y - y0) / (y1 - y0)))
        d.line([(0, y), (S, y)], fill=tuple(int(a + (b - a) * t) for a, b in zip(top, bot)) + (255,))
    return g


def solid(rgb):
    return Image.new("RGBA", (S, S), rgb + (255,))


def main():
    out = sys.argv[1]
    size = int(sys.argv[2]) if len(sys.argv) > 2 else 256
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    r = 470

    # drop shadow under the badge
    sh = Image.new("L", (S, S), 0)
    ImageDraw.Draw(sh).ellipse((C - r, C - r + 18, C + r, C + r + 18), fill=150)
    img.paste(solid((0, 0, 0)), (0, 0), sh.filter(ImageFilter.GaussianBlur(16)))

    # badge: gunmetal rim, then dark teal visor glass with a cyan glow behind the X
    rim = Image.new("L", (S, S), 0)
    ImageDraw.Draw(rim).ellipse((C - r, C - r, C + r, C + r), fill=255)
    img.paste(vgrad((214, 226, 232), (58, 70, 82), C - r, C + r), (0, 0), rim)
    face_r = r - 34
    face = Image.new("L", (S, S), 0)
    ImageDraw.Draw(face).ellipse((C - face_r, C - face_r, C + face_r, C + face_r), fill=255)
    img.paste(vgrad((10, 44, 54), (2, 8, 12), C - face_r, C + face_r), (0, 0), face)
    glow = Image.new("L", (S, S), 0)
    ImageDraw.Draw(glow).ellipse((C - 300, C - 300, C + 300, C + 300), fill=140)
    glow = ImageChops.multiply(glow.filter(ImageFilter.GaussianBlur(90)), face)
    img.paste(solid((40, 210, 240)), (0, 0), glow)

    # visor scanlines: faint horizontal lines across the glass
    lines = Image.new("L", (S, S), 0)
    d = ImageDraw.Draw(lines)
    for y in range(0, S, 12):
        d.line([(0, y), (S, y)], fill=26, width=3)
    img.paste(solid((120, 240, 255)), (0, 0), ImageChops.multiply(lines, face))

    # scan reticle: a broken ring and four corner brackets, cyan, glowing
    ret = Image.new("L", (S, S), 0)
    d = ImageDraw.Draw(ret)
    rr = face_r - 46
    for a0 in (20, 110, 200, 290):
        d.arc((C - rr, C - rr, C + rr, C + rr), a0, a0 + 50, fill=255, width=14)
    b, L, w = face_r - 120, 70, 12
    for sx in (-1, 1):
        for sy in (-1, 1):
            x, y = C + sx * b * 0.72, C + sy * b * 0.72
            d.line([(x, y), (x - sx * L, y)], fill=255, width=w)
            d.line([(x, y), (x, y - sy * L)], fill=255, width=w)
    ret = ImageChops.multiply(ret, face)
    halo = ImageChops.lighter(ret, ret.filter(ImageFilter.GaussianBlur(14)))
    img.paste(solid((110, 236, 255)), (0, 0), halo.point(lambda v: v * 210 // 255))

    # the X: dark outline, a Varia orange-to-red body, a bevel lit from the top left
    length, width, cut = 680, 160, 58
    outline = x_mask(length + 56, width + 56, cut + 23)
    body = x_mask(length, width, cut)
    img.paste(solid((6, 14, 20)), (0, 0), outline)
    img.paste(vgrad((255, 226, 120), (196, 34, 12), C - length / 2, C + length / 2), (0, 0), body)

    # bevel: the mask's edge, offset one way lit and the other way shaded
    edge = ImageChops.subtract(body, body.filter(ImageFilter.MinFilter(31)))
    lit = ImageChops.multiply(ImageChops.offset(edge, 6, 6), body)
    shade = ImageChops.multiply(ImageChops.offset(edge, -6, -6), body)
    img.paste(solid((255, 250, 225)), (0, 0), lit.point(lambda v: v * 130 // 255))
    img.paste(solid((110, 12, 0)), (0, 0), shade.point(lambda v: v * 150 // 255))

    # gloss: a soft white sheen on the upper half of the X
    gloss = Image.new("L", (S, S), 0)
    ImageDraw.Draw(gloss).ellipse((C - 420, C - 520, C + 420, C - 20), fill=60)
    gloss = ImageChops.multiply(gloss.filter(ImageFilter.GaussianBlur(30)), body.filter(ImageFilter.MinFilter(15)))
    img.paste(solid((255, 255, 255)), (0, 0), gloss)

    # energy core where the arms cross: a small green-cyan orb with a cross flare
    core = Image.new("L", (S, S), 0)
    d = ImageDraw.Draw(core)
    d.ellipse((C - 34, C - 34, C + 34, C + 34), fill=255)
    d.polygon([(C, C - 150), (C + 16, C), (C, C + 150), (C - 16, C)], fill=200)
    d.polygon([(C - 150, C), (C, C - 16), (C + 150, C), (C, C + 16)], fill=200)
    core = ImageChops.lighter(core.filter(ImageFilter.GaussianBlur(3)), core.filter(ImageFilter.GaussianBlur(26)))
    img.paste(solid((200, 255, 240)), (0, 0), core.point(lambda v: v * 220 // 255))

    img.resize((size, size), Image.LANCZOS).save(out)
    print(f"wrote {out} ({size}x{size})")


if __name__ == "__main__":
    main()
