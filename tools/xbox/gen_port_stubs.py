#!/usr/bin/env python3
"""Generate "feature off" definitions for the Port* hooks the game calls that
Prime-X drops (docs/decisions.md "How TARGET_PC code is carried").

Input: the link's undefined symbols as lld-link prints them (demangled MSVC
signatures), one per line; output: a C++ file defining each one so it does
nothing and returns a value-initialized result (false, 0, nullptr, an empty
object; a reference return points at a static empty object). Each logs
"[STUB] name" the first time it runs, so the log says which ones the game
reached.

  python tools/xbox/gen_port_stubs.py build-xbox/undef.txt xbox/src/port/port_stubs_gen.cpp \\
      --headers xbox/src/port/stub_headers.txt

Only names matching --include (default: Port*, Musyx*, aurora) are generated;
the rest (SDK functions, game members) are listed on stderr. Review the
output: a hook whose "off" is not zero needs a hand-written definition
(xbox/src/port/*.cpp) instead, and the list in --exclude.
"""
import argparse
import re
import sys

CALLCONV = re.compile(r'\s(__cdecl|__thiscall|__stdcall|__fastcall|__vectorcall)\s')


def clean(t):
    t = re.sub(r'\b(class|struct|enum|union)\s+', '', t)
    t = t.replace('unsigned __int64', 'unsigned long long').replace('__int64', 'long long')
    t = t.replace('std::__1::', 'std::').replace('`anonymous namespace\'', '')
    t = re.sub(r'\s+([*&])', r'\1', t)
    return t.strip()


def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '<(':
            depth += 1
        elif ch in '>)':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out]


def parse(sig):
    """-> (kind, ret, qualname, params, const) or None"""
    m = CALLCONV.search(' ' + sig + ' ')
    if not m:
        # data: "<type> <qualname>"
        m = re.match(r'^(.*\S)\s+([A-Za-z_][\w:<>, ]*)$', sig)
        if not m or '(' in sig:
            return None
        return ('data', clean(m.group(1)), m.group(2).strip(), None, False)
    head, tail = sig[:m.start()], sig[m.end() - 1:]
    head = re.sub(r'^(public|private|protected):\s*', '', head)
    static = 'static ' in head
    head = re.sub(r'\b(static|virtual)\s+', '', head)
    i = tail.index('(')
    # the parameter list is the last top-level (...) group
    depth, j = 0, len(tail) - 1
    while j >= 0:
        if tail[j] == ')':
            depth += 1
        elif tail[j] == '(':
            depth -= 1
            if depth == 0:
                break
        j -= 1
    name, params, after = tail[:j].strip(), tail[j + 1:tail.rindex(')')], tail[tail.rindex(')') + 1:]
    params = [] if params.strip() in ('', 'void') else [clean(p) for p in split_params(params)]
    return ('func', clean(head), clean(name), params, 'const' in after)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('undef')
    ap.add_argument('out')
    ap.add_argument('--headers', help='file listing the #include lines to put at the top')
    ap.add_argument('--include', default=r'Port|Musyx|aurora')
    ap.add_argument('--exclude', default='', help='file of qualified names to leave out')
    args = ap.parse_args()
    keep = re.compile(args.include)
    exclude = set()
    if args.exclude:
        exclude = {l.strip() for l in open(args.exclude) if l.strip() and not l.startswith('#')}
    lines = [l.strip() for l in open(args.undef) if l.strip()]
    out = ['// Generated by tools/xbox/gen_port_stubs.py: dropped Port* hooks, "off".',
           '// Do not edit; hand-written hooks live in the other xbox/src/port files.',
           '#include "px_stub.h"']
    if args.headers:
        out += [l.rstrip() for l in open(args.headers) if l.strip()]
    out.append('')
    skipped = []
    n = 0
    for sig in lines:
        if not keep.search(sig) or sig.startswith('_'):
            skipped.append(sig)
            continue
        p = parse(sig)
        if not p:
            skipped.append(sig)
            continue
        kind, ret, name, params, const = p
        if name in exclude:
            continue
        if kind == 'data':
            out.append(f'{ret} {name}{{}};')
        else:
            # type_identity: a function-pointer or array parameter takes a name anywhere
            args_ = ', '.join(f'std::type_identity_t< {t} > a{i}' for i, t in enumerate(params))
            rett = f'std::type_identity_t< {ret} >' if '(' in ret or '[' in ret else ret
            if ret in ('void', ''):   # also constructors and destructors
                body = f'PX_STUB("{name}"); '
            elif params and params[0] in (f'{ret} const&', f'const {ret}&'):
                # a filter over a value (a camera view, a transform): off passes it through
                body = f'PX_STUB("{name}"); return a0; '
            else:
                body = f'PX_STUB("{name}"); return px_stub_value< {ret} >(); '
            out.append(f'{rett} {name}({args_}){" const" if const else ""} {{ {body}}}')
        n += 1
    open(args.out, 'w', newline='\n').write('\n'.join(out) + '\n')
    print(f'{n} stubs -> {args.out}; {len(skipped)} other undefined symbols', file=sys.stderr)
    for s in skipped:
        print('  ' + s, file=sys.stderr)


if __name__ == '__main__':
    main()
